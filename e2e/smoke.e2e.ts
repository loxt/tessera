const toPlaywright = (accel: string) =>
  accel
    .split('+')
    .map((p) => ({ Cmd: 'Meta', Ctrl: 'Control', Up: 'ArrowUp', Down: 'ArrowDown', Left: 'ArrowLeft', Right: 'ArrowRight', Space: ' ' })[p] ?? p)
