async function launch(): Promise<{ app: ElectronApplication; page: Page }> {
  // TESSERA_EXECUTABLE=dist/mac-arm64/Tessera.app/Contents/MacOS/Tessera tests the packaged app
  const packaged = process.env.TESSERA_EXECUTABLE
  const app = await electron.launch({
    executablePath: packaged ?? ((await import('electron')).default as unknown as string),
    args: packaged ? [] : [join(root, 'out/main/index.js')],
    // the AI assistant talks to a scripted stand-in for Claude Code
    env: { ...process.env, TESSERA_USER_DATA: profile, ELECTRON_RENDERER_URL: '', TESSERA_CLAUDE_PATH: join(root, 'e2e/fake-claude.sh'), TESSERA_FAKE_CLAUDE_LOG: claudeLog }
  })
  const page = await app.firstWindow()
  page.on('pageerror', (err) => console.error('  [renderer error]', err.stack ?? err.message))
  page.on('console', (msg) => msg.type() === 'error' && console.error('  [renderer console]', msg.text()))
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.waitForSelector('.app .toolbar')
  return { app, page }
}

async function pickTheme(page: Page, name: string) {
  await page.locator('.toolbar button[title="Choose theme"]').click()
  await page.locator('.palette .input').fill(name)
  await page.locator('.palette-item', { hasText: name }).first().click()
}

async function typeSql(page: Page, sql: string) {
  const editor = page.locator('.tab-page:not([hidden]) .monaco-editor').first()
  await editor.click()
  await page.keyboard.press('Meta+A')
  await page.keyboard.press('Backspace')
  await page.keyboard.insertText(sql)
}

async function execute(page: Page) {
  await page.locator('.tab-page:not([hidden]) button[title^="Execute ("]').click()
  await page.locator('.tab-page:not([hidden]) .query-progress').waitFor({ state: 'detached', timeout: 20_000 })
}

async function pgReachable(): Promise<boolean> {
  const { Client } = await import('pg')
  const c = new Client({ host: '127.0.0.1', port: 55432, user: 'tessera', password: 'tessera', database: 'shop', connectionTimeoutMillis: 1500 })
  try {
    await c.connect()
    await c.end()
    return true
  } catch {
    return false
  }
}

