-- Tessera "shop" fixture (PostgreSQL). Deterministic seed for integration tests and manual QA.

CREATE TABLE customers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email varchar(255) UNIQUE,
  created_at timestamp NOT NULL DEFAULT now(),
  active boolean NOT NULL DEFAULT true
);
COMMENT ON TABLE customers IS 'People who buy things';

CREATE TABLE products (
  id serial PRIMARY KEY,
  sku varchar(32) NOT NULL UNIQUE,
  title text NOT NULL,
  price numeric(10,2) NOT NULL,
  data jsonb,
  image bytea,
  big_counter bigint
);

CREATE TABLE orders (
  id serial PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers(id),
  created_at timestamp NOT NULL DEFAULT now(),
  status varchar(16) NOT NULL DEFAULT 'new'
);
CREATE INDEX orders_customer_id_idx ON orders (customer_id);

CREATE TABLE order_items (
  order_id integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id integer NOT NULL REFERENCES products(id),
  qty integer NOT NULL CHECK (qty > 0),
  PRIMARY KEY (order_id, product_id)
);

CREATE TABLE audit_log (
  msg text,
  at timestamp
);

CREATE VIEW order_totals AS
SELECT o.id AS order_id, o.customer_id, sum(i.qty * p.price) AS total
FROM orders o
JOIN order_items i ON i.order_id = o.id
JOIN products p ON p.id = i.product_id
GROUP BY o.id, o.customer_id;

CREATE FUNCTION order_count(cid int) RETURNS bigint
LANGUAGE sql STABLE AS $$ SELECT count(*) FROM orders WHERE customer_id = cid $$;

CREATE SEQUENCE invoice_seq START 1000 INCREMENT 10;

CREATE SCHEMA analytics;
CREATE TABLE analytics.daily_sales (
  day date PRIMARY KEY,
  revenue numeric(12,2) NOT NULL
);

